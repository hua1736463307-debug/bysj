const { test, expect } = require('@playwright/test')
const fs = require('node:fs'), path = require('node:path')
const apiURL = process.env.BYSJ_E2E_API || 'http://127.0.0.1:18000/api/v1'

test('real v1 workflow: 24 images, three pages, freeze, GPU train, evaluate, infer, export, review', async ({ page, request }, info) => {
  if (!['127.0.0.1','localhost'].includes(new URL(apiURL).hostname)) throw new Error('E2E only accepts explicitly isolated local deployments')
  const dataRoot = process.env.BYSJ_E2E_DATA
  if (!dataRoot || !process.env.BYSJ_E2E_PASSWORD) throw new Error('Set BYSJ_E2E_DATA and BYSJ_E2E_PASSWORD for real acceptance')
  const requests = [], errors = [], ids = {}
  page.on('request', r => { const url = new URL(r.url()); if(url.pathname.startsWith('/api')) requests.push({method:r.method(),path:url.pathname}) })
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/login')
  await page.getByPlaceholder('请输入用户名').fill(process.env.BYSJ_E2E_USERNAME || 'admin')
  await page.getByPlaceholder('请输入密码').fill(process.env.BYSJ_E2E_PASSWORD)
  await page.getByRole('button',{name:'登 录'}).click()
  await expect(page).toHaveURL(/raw-dataset/)
  const token = await page.evaluate(()=>localStorage.getItem('token'))
  const headers = { Authorization: `Bearer ${token}` }
  async function data(url) { const response=await request.get(apiURL+url,{headers});expect(response.ok()).toBeTruthy();return (await response.json()).data }
  async function waitJob(id) { await expect.poll(async()=>(await data('/jobs/'+id)).status,{timeout:180000,intervals:[1000,2000]}).toMatch(/^(completed|failed|cancelled|interrupted)$/);const job=await data('/jobs/'+id);expect(job.status,JSON.stringify(job.error)).toBe('completed');return job }
  const images=fs.readdirSync(path.join(dataRoot,'images')).filter(n=>/\.(jpg|png|jpeg)$/i.test(n)).sort().slice(0,24)
  expect(images.length).toBe(24)
  const files=images.flatMap(n=>[path.join(dataRoot,'images',n),path.join(dataRoot,'labels',n.replace(/\.[^.]+$/,'.txt'))])
  const name='browser-acceptance-'+Date.now()
  await page.getByLabel('数据集名称',{exact:true}).fill(name)
  await page.getByLabel('导入文件').setInputFiles(files)
  const importPromise=page.waitForResponse(r=>r.url().endsWith('/api/v1/datasets/import')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'开始导入'}).click()
  const importJob=(await (await importPromise).json()).data
  const imported=await waitJob(importJob.job_id);ids.import_job=imported.job_id
  ids.dataset_id=imported.result.dataset_id;ids.version_id=imported.result.version_id
  await page.getByRole('button',{name:'刷新列表'}).click()
  await page.getByRole('row').filter({hasText:name}).getByRole('link',{name:'标注',exact:true}).click()
  await expect(page.locator('.image-board img')).toBeVisible()
  await expect(page.getByText('第 1 / 3 页',{exact:false})).toBeVisible()
  const asset=(await data(`/datasets/${ids.dataset_id}/assets?version_id=${ids.version_id}`)).items[0]
  const before=(await data('/annotations/'+asset.asset_id)).annotations.length
  const board=page.locator('.image-board');const rect=await board.boundingBox()
  await page.mouse.move(rect.x+rect.width*.1,rect.y+rect.height*.1);await page.mouse.down();await page.mouse.move(rect.x+rect.width*.3,rect.y+rect.height*.3);await page.mouse.up()
  await page.getByRole('button',{name:'保存标注',exact:true}).click()
  await expect.poll(async()=>(await data('/annotations/'+asset.asset_id)).annotations.length).toBe(before+1)
  await page.getByRole('button',{name:'删除框 1',exact:true}).click();await page.getByRole('button',{name:'撤销',exact:true}).click()
  await page.getByRole('button',{name:'下一页',exact:true}).click();await expect(page.getByText('第 2 / 3 页',{exact:false})).toBeVisible()
  await page.getByRole('button',{name:'下一页',exact:true}).click();await expect(page.getByText('第 3 / 3 页',{exact:false})).toBeVisible()
  await page.reload();await expect(page.locator('.image-board img')).toBeVisible()
  expect((await data('/annotations/'+asset.asset_id)).annotations.length).toBe(before+1)
  await page.screenshot({path:info.outputPath('annotation.png'),fullPage:true})
  await page.getByRole('link',{name:'训练数据',exact:true}).click()
  await page.getByLabel('数据集',{exact:true}).selectOption(ids.dataset_id)
  await page.getByLabel('版本',{exact:true}).selectOption(ids.version_id)
  const freezePromise=page.waitForResponse(r=>r.url().endsWith(`/datasets/${ids.dataset_id}/versions`)&&r.request().method()==='POST')
  await page.getByRole('button',{name:'冻结版本',exact:true}).click()
  ids.freeze_job=(await (await freezePromise).json()).data.job_id;await waitJob(ids.freeze_job)
  await page.getByRole('button',{name:'刷新数据',exact:true}).click()
  await page.getByLabel('版本',{exact:true}).selectOption(ids.version_id)
  const tilePromise=page.waitForResponse(r=>r.url().endsWith(`/datasets/${ids.dataset_id}/train-tile-versions`)&&r.request().method()==='POST')
  await page.getByRole('button',{name:'创建切片版本',exact:true}).click()
  ids.tile_job=(await (await tilePromise).json()).data.job_id
  ids.tile_version=(await waitJob(ids.tile_job)).result.version_id
  const tileVersion=await data('/dataset-versions/'+ids.tile_version)
  expect(tileVersion.state).toBe('frozen');expect(tileVersion.parent_version_id).toBe(ids.version_id)
  const parentVersion=await data('/dataset-versions/'+ids.version_id)
  expect(tileVersion.split_counts.val).toBe(parentVersion.split_counts.val)
  expect(tileVersion.split_counts.test).toBe(parentVersion.split_counts.test)
  const base=(await data('/models?page_size=200')).items.find(m=>m.trusted_source==='base');expect(base).toBeTruthy()
  await page.getByRole('link',{name:'模型训练',exact:true}).click()
  await page.getByLabel('数据集',{exact:true}).selectOption(ids.dataset_id)
  await page.getByLabel('版本',{exact:true}).selectOption(ids.version_id)
  await page.getByLabel('训练模型',{exact:true}).selectOption(base.model_id)
  await page.getByRole('button',{name:'训练预检',exact:true}).click();await expect(page.getByText('预检通过',{exact:true})).toBeVisible()
  const trainPromise=page.waitForResponse(r=>r.url().endsWith('/training/jobs')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'提交训练',exact:true}).click()
  ids.training_job=(await (await trainPromise).json()).data.job_id
  const trained=await waitJob(ids.training_job);ids.model_id=trained.result.model_id
  await page.getByRole('link',{name:'模型管理',exact:true}).click()
  await page.getByRole('row').filter({hasText:ids.model_id}).getByRole('button',{name:'选择评估'}).click()
  await page.getByLabel('数据集',{exact:true}).selectOption(ids.dataset_id);await page.getByLabel('版本',{exact:true}).selectOption(ids.version_id)
  await page.getByLabel('评估用途').fill('工程浏览器验收，非正式实验')
  const evalPromise=page.waitForResponse(r=>r.url().endsWith('/evaluations')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'开始评估'}).click()
  const evaluation=(await (await evalPromise).json()).data;ids.evaluation_id=evaluation.evaluation.evaluation_id;await waitJob(evaluation.job.job_id)
  await page.getByRole('link',{name:'推理验证',exact:true}).click()
  await page.getByLabel('推理模型').selectOption(ids.model_id)
  await page.getByLabel('数据集',{exact:true}).selectOption(ids.dataset_id);await page.getByLabel('版本',{exact:true}).selectOption(ids.version_id)
  const trainAssets=(await data(`/datasets/${ids.dataset_id}/assets?version_id=${ids.version_id}&page_size=100`)).items.filter(a=>a.split==='train').slice(0,2)
  expect(trainAssets.length).toBe(2)
  for(const item of trainAssets) await page.getByLabel(item.basename,{exact:true}).check()
  const inferPromise=page.waitForResponse(r=>r.url().endsWith('/inference/images')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'所选资产推理'}).click()
  const infer=(await (await inferPromise).json()).data;ids.inference_run=infer.run_id;await waitJob(infer.job.job_id)
  await expect(page.getByRole('button',{name:'人工复核'}).first()).toBeVisible()
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'导出 JSON'}).click();const download=await downloadPromise;await download.saveAs(info.outputPath('inference.json'))
  await page.getByRole('button',{name:'人工复核'}).first().click()
  await page.getByLabel('补充漏检框').check();await page.getByLabel('复核说明').fill('合成工程复核，仅测试数据链路')
  const reviewPromise=page.waitForResponse(r=>r.url().endsWith('/reviews')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'提交人工复核'}).click()
  ids.review_id=(await (await reviewPromise).json()).data.review_id
  await page.getByRole('row').filter({hasText:ids.review_id}).getByRole('button',{name:'批准',exact:true}).click()
  const reviewRow=page.getByRole('row').filter({hasText:ids.review_id})
  await expect(reviewRow).toContainText('approved')
  await reviewRow.getByRole('checkbox').check()
  const feedbackPromise=page.waitForResponse(r=>r.url().endsWith('/reviews/export-version')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'生成反馈子版本'}).click()
  ids.feedback_job=(await (await feedbackPromise).json()).data.job_id
  ids.child_version_id=(await waitJob(ids.feedback_job)).result.child_version_id
  const child=await data('/dataset-versions/'+ids.child_version_id)
  expect(child.state).toBe('frozen');expect(child.parent_version_id).toBe(ids.version_id)
  await page.screenshot({path:info.outputPath('inference-review.png'),fullPage:true})
  expect(errors).toEqual([]);expect(requests.every(r=>r.path.startsWith('/api/v1/'))).toBeTruthy()
  fs.writeFileSync(info.outputPath('evidence.json'),JSON.stringify({ids,requests,consoleErrors:errors},null,2))
})
